"""ShieldWealth advisor console.

Run with:  uv run streamlit run streamlit_app.py
"""

import streamlit as st

st.set_page_config(page_title="ShieldWealth", page_icon="assets/icon.svg", layout="wide")

from app.pipeline import gemini_available  # noqa: E402
from ui import components as ui  # noqa: E402
from ui import state  # noqa: E402
from ui.views import book, methodology, onboarding, review  # noqa: E402

state.init()
ui.inject_css()

pages = {
    "book": st.Page(book.render, title="Client book", icon=":material/table_view:", url_path="book", default=True),
    "review": st.Page(review.render, title="Client review", icon=":material/fact_check:", url_path="review"),
    "new": st.Page(onboarding.render, title="New client", icon=":material/person_add:", url_path="new-client"),
    "method": st.Page(methodology.render, title="Methodology", icon=":material/menu_book:", url_path="methodology"),
}
st.session_state["pages"] = pages

st.logo("assets/logo.svg", size="large", icon_image="assets/icon.svg")
nav = st.navigation(list(pages.values()), position="top")

# Context bar: what this session is running against, with the controls one click away.
has_key = gemini_available()
bar_l, bar_r = st.columns([5, 1], vertical_alignment="center")
with bar_r.popover("Session", icon=":material/tune:", width="stretch"):
    choice = st.segmented_control(
        "Model", ["offline", "gemini"], key="mode_widget", format_func={"offline": "Offline", "gemini": "Gemini"}.get,
        help="Offline runs every agent with a deterministic stand-in model: no API key, no data leaves the machine. "
             "Gemini needs GOOGLE_API_KEY.",
    )
    st.session_state["mode"] = choice or "offline"
    if st.session_state["mode"] == "gemini" and not has_key:
        st.caption(":orange[No GOOGLE_API_KEY is set, so reviews run offline.]")
    st.selectbox("Market scenario", list(state.SCENARIOS), key="scenario", format_func=state.SCENARIOS.get,
                 help="Applies to the market scout, risk and planning agents.")

ctx = state.market(st.session_state["scenario"])
effective_gemini = st.session_state["mode"] == "gemini" and has_key
model_label = "Gemini 2.5 Flash" if effective_gemini else "Offline model"
model_dot = "#1e3a8a" if effective_gemini else "#16a34a"
bar_l.markdown(
    f'<div class="sw-context" role="status" aria-label="Session context">'
    f'<span><span class="sw-dot" style="background:{model_dot}"></span><b>{ui.h(model_label)}</b></span>'
    f'<span>Market: <b>{ui.h(state.SCENARIOS[st.session_state["scenario"]])}</b></span>'
    f'<span class="sw-num">VIX {ctx["vix"]} · 10Y {ctx["yield_10y"]}% · 3M {ctx["yield_3m"]}%</span>'
    f'<span>{ui.h(ctx["note"])}</span></div>',
    unsafe_allow_html=True,
)

nav.run()

ui.html('<p class="sw-disclaimer">Demonstration system with synthetic client data. Not investment advice. '
        'All figures are computed by the deterministic rules engine; language is generated by the selected model.</p>')
